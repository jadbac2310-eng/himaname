function pick(a, rnd) { return a[Math.floor(rnd() * a.length)]; }

function makeOne(rnd, mode) {
  const m = mode === 'mix' ? pick(['attr', 'mono', 'jukugo', 'naru'], rnd) : mode;
  if (m === 'jukugo') {
    const [n, k] = pick(JUKUGO, rnd);
    return { name: n, kana: k, note: '熟語', cat: 'jukugo' };
  }
  if (m === 'mono') {
    const [n, k] = pick(MONO, rnd);
    return { name: n, kana: k, note: '者系', cat: 'mono' };
  }
  if (m === 'naru') {
    const a = pick(ADJ_NARU, rnd), t = pick(TITLE, rnd);
    return { name: `${a[0]}なる${t[0]}`, kana: `${a[1]}なる${t[1]}`, note: '形容', cat: 'naru' };
  }
  const a = pick(ATTR, rnd), t = pick(TITLE, rnd);
  return { name: `${a[0]}の${t[0]}`, kana: `${a[1]}の${t[1]}`, note: '属性称号', cat: 'attr' };
}

const seedRandom = (seed) => {
  if (seed == null) return Math.random;
  let s = seed >>> 0;
  return () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 4294967296; };
};

export function generateEpithet({ mode = 'mix', count = 12, seed = null } = {}) {
  const rnd = seedRandom(seed);
  const out = [], seen = new Set();
  let guard = 0;
  while (out.length < count && guard++ < count * 30) {
    const x = makeOne(rnd, mode);
    if (seen.has(x.name)) continue;
    seen.add(x.name);
    out.push(x);
  }
  return out;
}
