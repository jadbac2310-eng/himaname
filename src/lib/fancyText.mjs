function tbl(table, ch) {
  const c = ch.codePointAt(0);
  if (c >= 65 && c <= 90) return table[c - 65] ?? ch;
  if (c >= 97 && c <= 122) return table[26 + (c - 97)] ?? ch;
  if (c >= 48 && c <= 57 && table.length >= 62) return table[52 + (c - 48)] ?? ch;
  return ch;
}
const mapStr = (text, table) => [...text].map((ch) => tbl(table, ch)).join('');
function squared(text) {
  return [...text].map((ch) => { const c = ch.toUpperCase().codePointAt(0); return (c >= 65 && c <= 90) ? SQUARED[c - 65] : ch; }).join('');
}
function flip(text) { return [...text.toLowerCase()].map((ch) => FLIP[ch] ?? ch).reverse().join(''); }
const combine = (text, mark) => [...text].map((ch) => ch + mark).join('');
const spaced = (text) => [...text].join(' ');

export const STYLES = [
  ['ボールド', (t) => mapStr(t, T.bold)],
  ['イタリック', (t) => mapStr(t, T.italic)],
  ['筆記体', (t) => mapStr(t, T.script)],
  ['ゴシック体', (t) => mapStr(t, T.fraktur)],
  ['二重線', (t) => mapStr(t, T.double)],
  ['等幅', (t) => mapStr(t, T.mono)],
  ['丸囲み', (t) => mapStr(t, T.circle)],
  ['四角囲み', squared],
  ['全角', (t) => mapStr(t, T.full)],
  ['スペース', spaced],
  ['下線', (t) => combine(t, '̲')],
  ['取り消し線', (t) => combine(t, '̶')],
  ['上下反転', flip],
];

export function convert(text) {
  const s = text || '';
  return STYLES.map(([name, fn]) => ({ name, out: fn(s) }));
}
